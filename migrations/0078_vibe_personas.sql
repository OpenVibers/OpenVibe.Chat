-- phase: expand
-- A face and a name for each Vibe conversation (the owner, 2026-11-12): made from what the chat is about,
-- remade when its topic changes. The persona belongs to the room and goes with it; the spend is what Chat's
-- own models cost for personas this month, so the owner's cap is real money and not a counter of attempts.
CREATE TABLE IF NOT EXISTS vibe_personas (
    room_id        bigint PRIMARY KEY REFERENCES rooms(id) ON DELETE CASCADE,
    name           text COLLATE "C" NOT NULL,
    glyph          text COLLATE "C" NOT NULL,
    hue            smallint NOT NULL,
    image_url      text COLLATE "C",
    topic          text COLLATE "C" NOT NULL,
    made_at        text COLLATE "C" NOT NULL DEFAULT ov_now(),
    checked_at     text COLLATE "C",
    checked_count  integer NOT NULL DEFAULT 0,
    generation     integer NOT NULL DEFAULT 1,
    CONSTRAINT vibe_personas_hue CHECK (hue >= 0 AND hue <= 359),
    CONSTRAINT vibe_personas_generation CHECK (generation >= 1)
);

CREATE TABLE IF NOT EXISTS vibe_persona_spend (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id     bigint REFERENCES rooms(id) ON DELETE SET NULL,
    month       text COLLATE "C" NOT NULL,
    kind        text COLLATE "C" NOT NULL,
    model       text COLLATE "C",
    cost_usd    numeric NOT NULL DEFAULT 0,
    run_id      text COLLATE "C",
    created_at  text COLLATE "C" NOT NULL DEFAULT ov_now(),
    CONSTRAINT vibe_persona_spend_kind CHECK (kind IN ('text', 'image'))
);
CREATE INDEX IF NOT EXISTS vibe_persona_spend_month ON vibe_persona_spend(month);

-- A chat is named after its first message until the person renames it. Once they do, a persona never
-- writes over their name; this is the flag that records it.
ALTER TABLE rooms ADD COLUMN IF NOT EXISTS vibe_title_locked smallint NOT NULL DEFAULT 0;
