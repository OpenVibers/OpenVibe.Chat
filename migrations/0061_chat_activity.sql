-- phase: expand
-- Activity (the bottom bar's fourth place): what happened to a person in Chat, newest first. Six kinds, each one
-- written when it happens and each row naming who, what, where and when (server/chat/activity.js):
--
--   mention        someone wrote @you in a room, a channel or a direct message
--   reply          someone answered one of your messages (rooms, channels, direct messages and global chat)
--   reaction       someone put a reaction on your message in a room or a channel
--   server_invite  someone invited you to a server
--   friend_accept  someone accepted your friend request
--   role           someone gave you a role in a server or a room
--
-- The actor's name is kept on the row (it is what they were called when it happened), the room, server,
-- conversation and message ids let a reader go back to the place, and read_at is when the person has seen it.
-- A reader still checks that the room is readable now (server/chat/activity.js): an activity is never a way
-- around a kick, a block or a room that is gone.
CREATE TABLE IF NOT EXISTS chat_activity (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            bigint NOT NULL,                       -- the person it happened to
    kind               text COLLATE "C" NOT NULL,
    actor_user_id      bigint,                                -- who did it (NULL for a service)
    actor_username     text COLLATE "C",
    actor_display_name text COLLATE "C",
    actor_avatar_url   text COLLATE "C",
    room_id            bigint REFERENCES rooms(id) ON DELETE CASCADE,
    server_id          bigint REFERENCES chat_servers(id) ON DELETE CASCADE,
    conversation_id    bigint REFERENCES dm_conversations(id) ON DELETE CASCADE,
    message_id         bigint,                                -- room_messages.id, dm_messages.id or chat_messages.id
    parent_id          bigint,                                -- the message that was answered
    scope              text COLLATE "C" NOT NULL DEFAULT 'none',
    excerpt            text COLLATE "C",                        -- enough of the message to know what it is about
    reaction           text COLLATE "C",
    role               text COLLATE "C",
    invite_code        text COLLATE "C",
    place_label        text COLLATE "C",                        -- where it happened, when it has no row to join
    place_href         text COLLATE "C",
    created_at         text COLLATE "C" NOT NULL DEFAULT ov_now(),
    read_at            text COLLATE "C",
    CHECK (kind IN ('mention', 'reply', 'reaction', 'server_invite', 'friend_accept', 'role')),
    CHECK (scope IN ('room', 'dm', 'global', 'server', 'friends', 'none'))
);
-- A person's feed, newest first (the cursor is the id).
CREATE INDEX IF NOT EXISTS idx_chat_activity_user ON chat_activity (user_id, id DESC);
-- The Activity dot: only what is not read yet.
CREATE INDEX IF NOT EXISTS idx_chat_activity_unread ON chat_activity (user_id) WHERE read_at IS NULL;
-- A reaction is one event per person and message: a changed reaction updates that row, taking it back removes it.
CREATE INDEX IF NOT EXISTS idx_chat_activity_reaction ON chat_activity (user_id, message_id, actor_user_id) WHERE kind = 'reaction';

-- A reply is a message that answers another one. The rooms and direct messages were the only places without it;
-- global chat and channel chat have kept reply_to_id since the first migration. Expand only: older releases
-- write and read the column as NULL.
ALTER TABLE room_messages ADD COLUMN IF NOT EXISTS reply_to_id bigint REFERENCES room_messages(id) ON DELETE SET NULL;
ALTER TABLE dm_messages ADD COLUMN IF NOT EXISTS reply_to_id bigint REFERENCES dm_messages(id) ON DELETE SET NULL;
