-- phase: expand
-- An inbox's actions (server/inbox/actions.js): the team's own https endpoints Vibe may ask while it answers a visitor,
-- such as "look up an order". Each call is signed with the action's secret and carries the verified visitor, if any.
CREATE TABLE IF NOT EXISTS inbox_actions (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inbox_id    text COLLATE "C" NOT NULL,
    name        text COLLATE "C" NOT NULL,                -- snake_case; Vibe sees it as the tool action_<name>
    description text NOT NULL,
    url         text NOT NULL,
    params      jsonb NOT NULL DEFAULT '[]'::jsonb,       -- [{ name, description }], every one a string Vibe must give
    secret      text NOT NULL,                            -- whsec_…, signs each call (openvibe-sdk/events delivery headers)
    created_by  bigint,
    created_at  text COLLATE "C" NOT NULL DEFAULT ov_now(),
    last_status integer,
    last_error  text,
    last_at     text COLLATE "C",
    UNIQUE (inbox_id, name)
);
