-- phase: expand
-- Address previews for messages (server/chat/link-previews.js). A message with one or more https addresses gets up
-- to three previews, fetched by a background job after the message is stored — never by the request. The rows live
-- apart from the message so the message itself is never rewritten by a lookup:
--
--   link_previews        one row per address on a message: the address's place in the message, its URL, and the
--                        preview as JSON text. The fields are data only (text and numbers), never markup.
--   link_preview_cache   what one address resolved to, kept a day: a second message with the same address shows the
--                        same preview without another fetch. `data` is NULL for "fetched, no preview".
--
-- Expand only: two new tables; older releases never read or write them and every existing query keeps working.
CREATE TABLE IF NOT EXISTS link_previews (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_scope text COLLATE "C" NOT NULL,          -- 'room' (chat and dm scopes join it later)
    message_id    bigint NOT NULL,
    position      smallint NOT NULL,                  -- 0..2, the address's order in the message
    url           text COLLATE "C" NOT NULL,          -- the address the preview is for
    data          text COLLATE "C" NOT NULL,          -- { url, site_name, title, description, image, kind, width, height }
    created_at    text COLLATE "C" NOT NULL DEFAULT ov_now(),
    UNIQUE (message_scope, message_id, position)
);
-- A message's previews are read together, in the order the addresses appeared.
CREATE INDEX IF NOT EXISTS idx_link_previews_message ON link_previews (message_scope, message_id, position);

CREATE TABLE IF NOT EXISTS link_preview_cache (
    url        text COLLATE "C" PRIMARY KEY,
    data       text COLLATE "C",                      -- the preview as JSON text; NULL = fetched, no preview
    fetched_at bigint NOT NULL                        -- epoch milliseconds; a day makes it stale
);
