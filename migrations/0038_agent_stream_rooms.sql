-- phase: expand
-- Agent Streams S5 (design 2026-11-06, plan-state-2026-10-22/AGENT-STREAMS-S5-COPILOT-DESIGN-2026-11-06.md):
-- the Co-pilot room (kind 'agent_stream', id `agent:<ags_id>`), what an agent may read of it (the digest),
-- the polls it runs, and the agent's own labelled chat identity.
--
-- The room is created by Live when a stream is public or unlisted (a private stream has no room). Its id is
-- `agent:<ags_id>`, which is not a room slug: it is a Live agent stream's public id, so the two agree without
-- a mapping table. The banner says what the room is before anyone types.
--
-- The digest is what chat said between two steps, and only that: the agent never reads the raw room. The
-- filters (a timed-out or banned person, an account younger than a day, a person who set 'Agents don't read my
-- messages') are applied when the digest is made, and the cursor says how far it has read.
--
-- A poll can only choose between the options the agent wrote: Chat never adds one. One vote per person, one
-- poll at a time, at most one poll every five minutes, and the owner (or a moderator) can close or veto it.
--
-- Expand only: the room kind is a value in an existing column, every table here is new, and an older release
-- ignores all of it.

-- The room kind: 'agent_stream' joins the room kinds a Co-pilot stream's chat uses.
DO $$ BEGIN
    ALTER TABLE rooms DROP CONSTRAINT IF EXISTS rooms_kind_allowed;
    ALTER TABLE rooms ADD CONSTRAINT rooms_kind_allowed CHECK (kind IN ('community', 'call', 'system', 'agent_stream'));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- What an agent may read of a room, and how far it has read. The cursor is per room and per reader (the
-- task's service reads for the stream's owner), so two streams never share a cursor.
CREATE TABLE IF NOT EXISTS agent_room_reads (
    room_id          bigint NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
    reader           text COLLATE "C" NOT NULL,          -- who reads it: the task's service for the owner
    last_read_at     timestamptz,
    last_message_id  bigint NOT NULL DEFAULT 0,
    last_read_at_ms  bigint NOT NULL DEFAULT 0,          -- when the last read happened, for the 20 s limit
    updated_at       timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (room_id, reader)
);

-- The polls an agent asks a Co-pilot room to run.
CREATE TABLE IF NOT EXISTS agent_room_polls (
    id              text COLLATE "C" PRIMARY KEY,        -- pol_<ULID>
    room_id         bigint NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
    question        text COLLATE "C" NOT NULL,
    options         jsonb NOT NULL,                      -- [{ id: '1'..'4', label }] as the agent wrote them
    opened_at       timestamptz NOT NULL DEFAULT now(),
    closes_at       timestamptz NOT NULL,
    closed_at       timestamptz,
    state           text COLLATE "C" NOT NULL DEFAULT 'open' CHECK (state IN ('open', 'closed', 'vetoed')),
    result          jsonb,                               -- { counts: [...], total, winner } once it is closed
    vetoed_by       text COLLATE "C",
    asked_by        text COLLATE "C" NOT NULL,           -- the task's service that asked for it
    created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS agent_room_polls_room ON agent_room_polls (room_id, opened_at DESC);
CREATE INDEX IF NOT EXISTS agent_room_polls_open ON agent_room_polls (room_id) WHERE state = 'open';

-- Who voted for what. One vote per person: the primary key is the person and the poll.
CREATE TABLE IF NOT EXISTS agent_room_poll_votes (
    poll_id       text COLLATE "C" NOT NULL REFERENCES agent_room_polls(id) ON DELETE CASCADE,
    user_id       bigint NOT NULL,
    option_id     text COLLATE "C" NOT NULL,
    voted_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (poll_id, user_id)
);
CREATE INDEX IF NOT EXISTS agent_room_poll_votes_poll ON agent_room_poll_votes (poll_id);

-- The agent's own chat identity in the room: labelled 'AI agent', and one message every 20 seconds.
CREATE TABLE IF NOT EXISTS agent_room_identities (
    room_id        bigint PRIMARY KEY REFERENCES rooms(id) ON DELETE CASCADE,
    label          text COLLATE "C" NOT NULL DEFAULT 'AI agent',
    handle         text COLLATE "C" NOT NULL DEFAULT 'aiagent',
    last_message_at timestamptz,
    created_at     timestamptz NOT NULL DEFAULT now()
);

-- Every control the owner and the channel's moderators pressed over a Co-pilot stream, and who pressed it.
-- Live writes these (the room is Live's to moderate), Chat keeps them so the room can show the log.
CREATE TABLE IF NOT EXISTS agent_room_controls (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id      bigint NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
    control      text COLLATE "C" NOT NULL CHECK (control IN ('pause', 'curtain', 'mute', 'end')),
    by_handle    text COLLATE "C" NOT NULL,
    by_role      text COLLATE "C" NOT NULL CHECK (by_role IN ('owner', 'moderator')),
    paused_by    text COLLATE "C",
    at           timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS agent_room_controls_room ON agent_room_controls (room_id, at DESC);

-- A reaction on a room message, so the digest can count the thumbs up. One reaction per person and message:
-- pressing the same one again takes it back.
CREATE TABLE IF NOT EXISTS room_message_reactions (
    message_id  bigint NOT NULL REFERENCES room_messages(id) ON DELETE CASCADE,
    user_id     bigint NOT NULL,
    reaction    text COLLATE "C" NOT NULL CHECK (reaction IN ('thumbsup', 'thumbsdown', 'heart', 'laugh', 'surprised', 'sad')),
    created_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (message_id, user_id)
);
CREATE INDEX IF NOT EXISTS room_message_reactions_message ON room_message_reactions (message_id);

-- A person who is timed out in a room is left out of that room's digest (the design's filters).
CREATE TABLE IF NOT EXISTS room_member_timeouts (
    room_id    bigint NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
    user_id    bigint NOT NULL,
    until_at   timestamptz NOT NULL,
    by_handle  text COLLATE "C",
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (room_id, user_id)
);

-- The agent's answer line in the room (the agent's own chat identity, labelled 'AI agent'): an ordinary message
-- row marked as the agent's, so the room can label it without a second author table. Expand only.
ALTER TABLE room_messages ADD COLUMN IF NOT EXISTS agent_stream boolean NOT NULL DEFAULT false;
