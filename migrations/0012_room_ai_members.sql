-- phase: expand
-- AI members of a room (server/rooms/ai-members.js; owner 2026-09-28 Q14: friend groups and couples with AI members,
-- Q15: a Food household's chat with an AI member that knows the pantry). A room's managers add one with a name and how
-- it should be; when someone writes @handle in the room, it answers through OpenVibe.AI (chat.member.reply) and its
-- reply is a room message with ai_member_id set (user_id 0: no person wrote it).
CREATE TABLE IF NOT EXISTS room_ai_members (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id             bigint NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
    name                text COLLATE "C" NOT NULL,              -- shown in the room (2-24 characters)
    handle              text COLLATE "C" NOT NULL,              -- lowercase, what @mentions match
    persona             text NOT NULL DEFAULT '',               -- how the room wants it to be (<= 1000)
    memory              text NOT NULL DEFAULT '',               -- the room's notes for it (<= 2000)
    link_service        text COLLATE "C",                       -- a service that gives it shared context: 'food'
    link_resource       text COLLATE "C",                       -- that service's id for it: a Food household
    enabled             bigint NOT NULL DEFAULT 1,
    created_by_subject  text COLLATE "C",                       -- usr_… (NULL once that account is deleted)
    created_at          text COLLATE "C" DEFAULT ov_now(),
    updated_at          text COLLATE "C" DEFAULT ov_now(),
    UNIQUE (room_id, handle)
);

ALTER TABLE room_messages ADD COLUMN IF NOT EXISTS ai_member_id bigint;

-- Replies per room per UTC day (the room's daily cap).
CREATE TABLE IF NOT EXISTS room_ai_usage (
    room_id  bigint NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
    day      text COLLATE "C" NOT NULL,
    replies  integer NOT NULL DEFAULT 0,
    PRIMARY KEY (room_id, day)
);
