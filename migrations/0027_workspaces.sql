-- Workspace rooms (server/rooms/workspace.js; owner 2026-10-25: "one dedicated screen that all admins can share … the
-- same system as chat where we have an AI assistant but multi-user … see the queue and see what's being worked on").
-- A workspace room has a work queue beside its conversation: anyone who may post adds a task (or asks Vibe to), the
-- quick kinds run at once as OpenVibe.Actor tasks of the person who asked, the rest wait for a worker (a person, or
-- an agent with the room's worker grant) to claim them, and every result comes back into the room.
ALTER TABLE rooms ADD COLUMN IF NOT EXISTS workspace integer NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS room_tasks (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id            bigint NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
    title              text NOT NULL,                       -- what to do, one line (<= 200)
    details            text NOT NULL DEFAULT '',            -- everything else the worker needs (<= 6000)
    kind               text COLLATE "C" NOT NULL DEFAULT 'research'
                       CHECK (kind IN ('answer', 'research', 'web', 'code', 'computer', 'other')),
    status             text COLLATE "C" NOT NULL DEFAULT 'queued'
                       CHECK (status IN ('queued', 'running', 'succeeded', 'failed', 'cancelled')),
    requested_by       bigint NOT NULL,                     -- Chat user id of the person who asked
    requested_subject  text COLLATE "C",                    -- their usr_… (Actor runs quick kinds as them)
    via                text COLLATE "C" NOT NULL DEFAULT 'person' CHECK (via IN ('person', 'vibe', 'api')),
    source_message     bigint,                              -- the room message the task came from
    runner             text COLLATE "C",                    -- 'actor' or who claimed it: 'user:<id>' or an agent's name
    actor_task         text COLLATE "C",                    -- OpenVibe.Actor's task id (quick kinds)
    result             text,                                -- the answer or report (<= 20000)
    result_url         text,                                -- where the work landed (a pull request, a page)
    sources            text NOT NULL DEFAULT '[]',          -- JSON list of source links
    error              text,
    cost_usd           double precision,
    posted_message     bigint,                              -- the room message that announced the result
    created_at         text COLLATE "C" DEFAULT ov_now(),
    updated_at         text COLLATE "C" DEFAULT ov_now(),
    started_at         text COLLATE "C",
    finished_at        text COLLATE "C"
);
CREATE INDEX IF NOT EXISTS room_tasks_room_idx ON room_tasks (room_id, id DESC);
CREATE INDEX IF NOT EXISTS room_tasks_open_idx ON room_tasks (status, id) WHERE status IN ('queued', 'running');
CREATE INDEX IF NOT EXISTS room_tasks_requester_idx ON room_tasks (requested_by);

