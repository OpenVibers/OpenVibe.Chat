-- phase: expand
-- An inbox's webhooks (server/inbox/webhooks.js): the team's own systems, Slack or Discord hear when a visitor waits for
-- a person, writes, or rates a conversation. https on the public internet only; the secret signs the openvibe format.
CREATE TABLE IF NOT EXISTS inbox_webhooks (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inbox_id    text COLLATE "C" NOT NULL,
    url         text NOT NULL,
    format      text COLLATE "C" NOT NULL DEFAULT 'openvibe' CHECK (format IN ('openvibe', 'slack', 'discord')),
    secret      text,                                     -- whsec_…, the openvibe format only
    created_by  bigint,
    created_at  text COLLATE "C" NOT NULL DEFAULT ov_now(),
    last_status integer,
    last_error  text,
    last_at     text COLLATE "C",
    failures    integer NOT NULL DEFAULT 0,
    disabled_at text COLLATE "C",
    UNIQUE (inbox_id, url)
);
