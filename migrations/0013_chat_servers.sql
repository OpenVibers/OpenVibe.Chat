-- phase: expand
-- Servers (owner 2026-09-28 Q14: friend groups and couples first, then communities with servers, channels and voice):
-- a server is a group of rooms, its channels, with one membership and one set of roles for all of them
-- (server/rooms/servers.js). A channel is an ordinary room with server_id set: text channels are community rooms,
-- voice channels are call rooms, so messages, live delivery, calls and AI members work in them unchanged. A
-- channel's room_members rows only keep where each person read up to; what they may do comes from the server.
CREATE TABLE IF NOT EXISTS chat_servers (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug           text COLLATE "C" UNIQUE NOT NULL,          -- /s/<slug>
    name           text COLLATE "C" NOT NULL,                 -- 2-40 characters
    description    text COLLATE "C",                          -- <= 300 characters
    visibility     text COLLATE "C" NOT NULL DEFAULT 'public',-- public: listed, anyone reads, signed-in people join; private: invites only
    owner_id       bigint NOT NULL,
    owner_subject  text COLLATE "C",                          -- usr_… (NULL once that account is deleted)
    member_count   integer NOT NULL DEFAULT 0,
    created_at     text COLLATE "C" DEFAULT ov_now(),
    updated_at     text COLLATE "C" DEFAULT ov_now(),
    archived_at    text COLLATE "C",
    CHECK (visibility IN ('public', 'private'))
);
CREATE INDEX IF NOT EXISTS idx_chat_servers_public ON chat_servers (visibility, member_count DESC) WHERE archived_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_chat_servers_owner ON chat_servers (owner_id);

CREATE TABLE IF NOT EXISTS chat_server_members (
    server_id  bigint NOT NULL REFERENCES chat_servers(id) ON DELETE CASCADE,
    user_id    bigint NOT NULL,
    role       text COLLATE "C" NOT NULL DEFAULT 'member',   -- owner | admin | mod | member | blocked
    joined_at  text COLLATE "C" DEFAULT ov_now(),
    PRIMARY KEY (server_id, user_id),
    CHECK (role IN ('owner', 'admin', 'mod', 'member', 'blocked'))
);
CREATE INDEX IF NOT EXISTS idx_chat_server_members_user ON chat_server_members (user_id);

CREATE TABLE IF NOT EXISTS chat_server_invites (
    code        text COLLATE "C" PRIMARY KEY,                -- 10 characters, /join/<code>
    server_id   bigint NOT NULL REFERENCES chat_servers(id) ON DELETE CASCADE,
    created_by  bigint NOT NULL,
    created_by_subject text COLLATE "C",
    uses        integer NOT NULL DEFAULT 0,
    max_uses    integer,                                     -- NULL: no limit
    expires_at  text COLLATE "C",                            -- NULL: never
    revoked_at  text COLLATE "C",
    created_at  text COLLATE "C" DEFAULT ov_now()
);
CREATE INDEX IF NOT EXISTS idx_chat_server_invites_server ON chat_server_invites (server_id);

ALTER TABLE rooms ADD COLUMN IF NOT EXISTS server_id bigint REFERENCES chat_servers(id) ON DELETE CASCADE;
ALTER TABLE rooms ADD COLUMN IF NOT EXISTS channel_slug text COLLATE "C";      -- the channel's name in /s/<server>/<channel>
ALTER TABLE rooms ADD COLUMN IF NOT EXISTS position integer NOT NULL DEFAULT 0;
CREATE UNIQUE INDEX IF NOT EXISTS idx_rooms_server_channel ON rooms (server_id, channel_slug) WHERE server_id IS NOT NULL AND archived_at IS NULL;
