-- phase: expand
-- Support inboxes (docs/platform.md, the owner 2026-10-24: "the support box… DM style… direct live support with an agent"):
-- a team's inbox that any website embeds with openvibe.chat/widget.js. A visitor's conversation is answered first by Vibe
-- from the inbox's own instructions and pages, and by the inbox's people once handed off (server/inbox/inbox.js).
CREATE TABLE IF NOT EXISTS inboxes (
    id              text COLLATE "C" PRIMARY KEY,               -- inb_…
    owner_id        bigint NOT NULL,                            -- the person who made it (Live user id, like rooms.owner_id)
    owner_subject   text COLLATE "C",
    name            text NOT NULL,
    greeting        text NOT NULL DEFAULT '',
    color           text COLLATE "C" NOT NULL DEFAULT '#3b82f6',
    ai_enabled      smallint NOT NULL DEFAULT 1,
    ai_instructions text NOT NULL DEFAULT '',
    knowledge_urls  jsonb NOT NULL DEFAULT '[]',               -- pages Vibe may read to answer (https only)
    allowed_origins jsonb NOT NULL DEFAULT '[]',               -- sites that may embed it; [] = any site
    created_at      text COLLATE "C" NOT NULL DEFAULT ov_now(),
    archived_at     text COLLATE "C"
);
CREATE INDEX IF NOT EXISTS inboxes_owner ON inboxes (owner_id) WHERE archived_at IS NULL;

CREATE TABLE IF NOT EXISTS inbox_members (
    inbox_id  text COLLATE "C" NOT NULL,
    user_id   bigint NOT NULL,
    role      text COLLATE "C" NOT NULL DEFAULT 'agent' CHECK (role IN ('owner', 'agent')),
    added_at  text COLLATE "C" NOT NULL DEFAULT ov_now(),
    PRIMARY KEY (inbox_id, user_id)
);
CREATE INDEX IF NOT EXISTS inbox_members_user ON inbox_members (user_id);

-- One visitor's conversation with an inbox. status: bot (Vibe answers), waiting (asked for a person), open (a person
-- answered), resolved. The visitor is known by a token kept in the embed's own storage; only its hash is stored.
CREATE TABLE IF NOT EXISTS inbox_conversations (
    id                 text COLLATE "C" PRIMARY KEY,            -- cnv_…
    inbox_id           text COLLATE "C" NOT NULL,
    visitor_token_hash text COLLATE "C" NOT NULL,
    visitor_name       text,
    status             text COLLATE "C" NOT NULL DEFAULT 'bot' CHECK (status IN ('bot', 'waiting', 'open', 'resolved')),
    assignee_id        bigint,
    page_url           text,
    ai_replies         integer NOT NULL DEFAULT 0,
    agent_unread       integer NOT NULL DEFAULT 0,
    created_at         text COLLATE "C" NOT NULL DEFAULT ov_now(),
    last_message_at    text COLLATE "C"
);
CREATE INDEX IF NOT EXISTS inbox_conversations_inbox ON inbox_conversations (inbox_id, last_message_at DESC);
CREATE INDEX IF NOT EXISTS inbox_conversations_visitor ON inbox_conversations (inbox_id, visitor_token_hash);

CREATE TABLE IF NOT EXISTS inbox_messages (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id  text COLLATE "C" NOT NULL,
    author           text COLLATE "C" NOT NULL CHECK (author IN ('visitor', 'agent', 'ai', 'system')),
    author_user_id   bigint,
    author_name      text,
    body             text NOT NULL,
    created_at       text COLLATE "C" NOT NULL DEFAULT ov_now()
);
CREATE INDEX IF NOT EXISTS inbox_messages_conversation ON inbox_messages (conversation_id, id);

-- Vibe's answers per inbox per UTC day (its free allowance).
CREATE TABLE IF NOT EXISTS inbox_ai_usage (
    inbox_id  text COLLATE "C" NOT NULL,
    day       text COLLATE "C" NOT NULL,
    replies   integer NOT NULL DEFAULT 0,
    PRIMARY KEY (inbox_id, day)
);
