-- phase: expand
-- Agent Streams S6 (design 2026-11-06, plan-state-2026-10-22/AGENT-STREAMS-S6-CHAT-PLAYS-DESIGN-2026-11-06.md):
-- the chat plays queue — the requests a room makes for the desk, their votes, and what the owner and the
-- moderators do with them.
--
-- A request is made with '!do <request>' (at most 200 characters) in an agent stream's room. One open request
-- per person at a time, and an account younger than a day cannot ask. The request passes the house text
-- filters and the safety check before it is listed; a refused request never enters the queue and the room
-- gets one line saying why.
--
-- The request is a message of the room, so a thumbs up on it is a vote (as '!vote <n>' is). The queue is
-- read and written by Codes for the stream's owner (the capabilities chat.play_queue.read and
-- chat.play_queue.write); the people, the votes and the moderation belong to the room.
--
-- Expand only: every table here is new, the control table's check grows one value, and an older release
-- ignores all of it.

-- The requests of a room.
CREATE TABLE IF NOT EXISTS agent_play_requests (
    id              text COLLATE "C" PRIMARY KEY,      -- req_<ULID>
    room_id         bigint NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
    message_id      bigint,                           -- the request as a message of the room (the votes ride on it)
    user_id         bigint NOT NULL,
    subject_id      text COLLATE "C",
    handle          text COLLATE "C" NOT NULL,
    display_name    text COLLATE "C",
    text            text COLLATE "C" NOT NULL,
    state           text COLLATE "C" NOT NULL DEFAULT 'queued'
                    CHECK (state IN ('queued', 'running', 'done', 'failed', 'skipped', 'removed', 'refused')),
    pinned          boolean NOT NULL DEFAULT false,
    votes           integer NOT NULL DEFAULT 0,       -- kept for the overlay; the count is recomputed on read
    refusal_code    text COLLATE "C",                 -- why it was refused, when it was
    refusal_reason text COLLATE "C",
    outcome         text COLLATE "C",                 -- done, failed, timeout, budget or stopped
    result_line     text COLLATE "C",                 -- the one line the overlay and the voice said
    scratch_url     text COLLATE "C",
    task_id         text COLLATE "C",
    started_at      timestamptz,
    ended_at        timestamptz,
    created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS agent_play_requests_room ON agent_play_requests (room_id, created_at DESC);
CREATE INDEX IF NOT EXISTS agent_play_requests_open ON agent_play_requests (room_id) WHERE state IN ('queued', 'running');
CREATE UNIQUE INDEX IF NOT EXISTS agent_play_requests_one_open ON agent_play_requests (room_id, user_id)
    WHERE state IN ('queued', 'running');

-- A vote for a request: '!vote <n>' writes one; a thumbs up on the request's message counts too.
CREATE TABLE IF NOT EXISTS agent_play_votes (
    request_id  text COLLATE "C" NOT NULL REFERENCES agent_play_requests(id) ON DELETE CASCADE,
    user_id     bigint NOT NULL,
    via         text COLLATE "C" NOT NULL DEFAULT 'command' CHECK (via IN ('command', 'reaction')),
    voted_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (request_id, user_id)
);
CREATE INDEX IF NOT EXISTS agent_play_votes_request ON agent_play_votes (request_id);

-- The owner's log: every request, vote, skip, removal and pin of the room.
CREATE TABLE IF NOT EXISTS agent_play_log (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id     bigint NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
    action      text COLLATE "C" NOT NULL CHECK (action IN ('request', 'vote', 'skip', 'remove', 'pin', 'unpin', 'refused', 'wipe')),
    request_id  text COLLATE "C",
    by_handle   text COLLATE "C" NOT NULL,
    detail      text COLLATE "C",
    at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS agent_play_log_room ON agent_play_log (room_id, at DESC);

