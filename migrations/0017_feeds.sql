-- phase: expand
-- Feeds (docs/platform.md step 2, the owner 2026-10-24: "migrate that whole entire feature so it's built into the
-- openvibe.chat system"): live activity a person publishes into Chat with a feed's key; vibe coding, moved from
-- OpenVibe.Live, is the first kind. Viewers see a card in the feed's room, on its Live channel slot while live, or on any
-- site (openvibe.chat/embed/feed/:id). What they see is projected from the stored events by the feed's settings when
-- they see it (server/feeds/feeds.js).
CREATE TABLE IF NOT EXISTS feeds (
    id                text COLLATE "C" PRIMARY KEY,               -- fed_…
    owner_id          bigint NOT NULL,                            -- Live user id, like rooms.owner_id
    owner_subject     text COLLATE "C",
    kind              text COLLATE "C" NOT NULL DEFAULT 'coding' CHECK (kind IN ('coding')),
    title             text NOT NULL,
    room_id           bigint,                                     -- a Chat room it shows in (rooms.id)
    managed_stream_id bigint,                                     -- a Live channel slot it shows on while live
    settings          jsonb NOT NULL DEFAULT '{}',
    key_hash          text COLLATE "C",                           -- sha256 of the publish key (ovf_…), shown once
    key_hint          text COLLATE "C",                           -- its last four characters
    legacy_source     text COLLATE "C",                           -- 'live:managed_stream:<id>' when copied from Live
    created_at        text COLLATE "C" NOT NULL DEFAULT ov_now(),
    last_event_at     text COLLATE "C",
    archived_at       text COLLATE "C"
);
CREATE INDEX IF NOT EXISTS feeds_owner ON feeds (owner_id) WHERE archived_at IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS feeds_key ON feeds (key_hash) WHERE key_hash IS NOT NULL;
CREATE INDEX IF NOT EXISTS feeds_room ON feeds (room_id) WHERE room_id IS NOT NULL AND archived_at IS NULL;
CREATE INDEX IF NOT EXISTS feeds_slot ON feeds (managed_stream_id) WHERE managed_stream_id IS NOT NULL AND archived_at IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS feeds_legacy ON feeds (legacy_source) WHERE legacy_source IS NOT NULL;

-- One publisher's run (an editor window, an agent session): who published (integration, client, workspace) and when.
CREATE TABLE IF NOT EXISTS feed_sessions (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feed_id       text COLLATE "C" NOT NULL,
    session_key   text COLLATE "C" NOT NULL,
    publisher     jsonb NOT NULL DEFAULT '{}',
    status        text COLLATE "C" NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'ended')),
    created_at    text COLLATE "C" NOT NULL DEFAULT ov_now(),
    last_event_at text COLLATE "C",
    ended_at      text COLLATE "C",
    UNIQUE (feed_id, session_key)
);

-- The events as published (scrubbed of secrets and home folders on the way in). received_ms orders the feed's delay.
CREATE TABLE IF NOT EXISTS feed_events (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feed_id     text COLLATE "C" NOT NULL,
    session_key text COLLATE "C",
    event_id    text COLLATE "C" NOT NULL,
    seq         bigint NOT NULL DEFAULT 0,
    type        text COLLATE "C" NOT NULL,
    summary     text NOT NULL DEFAULT '',
    payload     jsonb NOT NULL,
    received_ms bigint NOT NULL,
    created_at  text COLLATE "C" NOT NULL DEFAULT ov_now(),
    UNIQUE (feed_id, event_id)
);
CREATE INDEX IF NOT EXISTS feed_events_feed ON feed_events (feed_id, id DESC);
